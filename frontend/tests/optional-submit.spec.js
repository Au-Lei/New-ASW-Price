import {test,expect} from '@playwright/test'
test('one confirmation; cancel retains edits; blank fields submit and publish',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin');await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!');await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe');await expect(app.locator('#view-home')).toBeVisible()
 await app.locator('#view-home .entry').last().click()
 const frame=page.frames().find(f=>f.url().includes('quotation.html'))
 await frame.evaluate(()=>{pane('edit',2);addRow()})
 await app.locator('input[data-k="remark"]').fill('虚构测试：空白字段审批');await app.locator('input[data-k="remark"]').blur()
 const messages=[];let accept=false;page.on('dialog',async d=>{messages.push(d.message());expect(d.type()).toBe('confirm');if(accept)await d.accept();else await d.dismiss()})
 const writes=[];page.on('request',r=>{if(r.method()!=='GET')writes.push(r.url())})
 await app.getByRole('button',{name:'提交审批 →',exact:true}).click()
 await expect(app.locator('#pane-edit')).toBeVisible();expect(writes).toEqual([])
 await expect(app.locator('input[data-k="remark"]')).toHaveValue('虚构测试：空白字段审批')
 accept=true
 await app.getByRole('button',{name:'提交审批 →',exact:true}).click()
 await expect(app.locator('#pane-diff')).toBeVisible()
 await expect(app.getByRole('button',{name:'✓ 审批通过并入库',exact:true})).toBeEnabled()
 expect(messages).toEqual(['你确定要提交吗，有些字段仍为空。','你确定要提交吗，有些字段仍为空。'])
 await app.getByRole('button',{name:'✓ 审批通过并入库',exact:true}).click()
 await expect(app.locator('#view-query')).toBeVisible()
 await app.locator('#q-etd').fill('2026-11-15');await app.getByRole('button',{name:'🔍 查询报价',exact:true}).click()
 await expect(app.locator('#q-table tbody')).toContainText('虚构测试：空白字段审批')
 const download=page.waitForEvent('download');await app.getByRole('button',{name:'📥 导出 Excel',exact:true}).click();expect((await download).suggestedFilename()).toContain('.xlsx')
 expect(errors).toEqual([])
})

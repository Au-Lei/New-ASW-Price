import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
test('real progress survives leaving and reload, completion is persistent and opens the correct result',async({page})=>{
 test.setTimeout(60000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe'),monitor=app.locator('#extraction-monitor')
 const buffer=readFileSync('/private/tmp/asw-progress-fixture-browser1/synthetic.xlsx')
 await app.locator('#view-home .entry').nth(1).click()
 await app.locator('#file-input').setInputFiles({name:'后台样本一.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer})
 await expect(app.locator('#filelist')).toContainText('已上传')
 await app.locator('#btn-extract').click()
 await expect(monitor).toContainText('后台样本一.xlsx')
 await expect(monitor).toContainText(/读取文件|本机解析表格|排队等待/)
 await expect(monitor).toContainText('已耗时')
 await app.locator('#view-update .back-link').click()
 await expect(app.locator('#view-home')).toBeVisible()
 await expect(monitor).toContainText('提取完成',{timeout:20000})
 await expect(app.locator('#view-home')).toBeVisible()
 expect(await page.frames().find(f=>f.url().includes('quotation.html')).evaluate(async()=>(await request('/api/manual-drafts')).items.length)).toBe(0)
 await monitor.getByRole('button',{name:'查看结果',exact:true}).click()
 await expect(app.locator('#pane-edit')).toBeVisible({timeout:10000})
 await expect(app.locator('#edit-table tbody tr')).toHaveCount(1)
 await monitor.getByRole('button',{name:/关闭.*提醒/}).click()
 await page.reload()
 await expect(app.locator('#view-home')).toBeVisible()
 await expect(monitor).toBeHidden()
 await app.locator('#view-home .entry').nth(1).click()
 await app.locator('#file-input').setInputFiles({name:'后台样本二.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer})
 await expect(app.locator('#filelist')).toContainText('后台样本二.xlsx')
 await app.locator('#btn-extract').click()
 await expect(monitor).toContainText('后台样本二.xlsx')
 await app.locator('#view-update .back-link').click()
 await page.reload()
 await expect(app.locator('#view-home')).toBeVisible()
 await expect(monitor).toContainText('后台样本二.xlsx')
 await expect(monitor).toContainText('提取完成',{timeout:20000})
 await expect(app.locator('#view-home')).toBeVisible()
 await monitor.getByRole('button',{name:'查看结果',exact:true}).click()
 await expect(app.locator('#pane-edit')).toBeVisible({timeout:10000})
 await expect(app.locator('#edit-table tbody tr')).toHaveCount(1)
 expect(errors).toEqual([])
 await page.screenshot({path:'/private/tmp/asw-background-progress-proof.png',fullPage:true})
})

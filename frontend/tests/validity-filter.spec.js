import {test,expect} from '@playwright/test'
test('validity buttons filter and expired delete confirms or cancels',async({page})=>{
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe')
 await app.locator('#view-home .entry').first().click()
 const stats=app.locator('#q-stat'),rows=app.locator('#q-table tbody tr')
 await stats.getByRole('button',{name:/有效期内/}).click()
 await expect(rows).toHaveCount(1)
 await stats.getByRole('button',{name:/即将到期/}).click()
 await expect(rows).toHaveCount(1)
 await stats.getByRole('button',{name:/有效期缺失/}).click()
 await expect(rows).toHaveCount(1)
 await stats.getByRole('button',{name:/^已过期/}).click()
 await expect(rows).toHaveCount(1)
 let accept=false,dialogs=0;page.on('dialog',async d=>{dialogs++;await (accept?d.accept():d.dismiss())})
 await stats.getByRole('button',{name:'一键删除过期报价',exact:true}).click()
 await expect.poll(()=>dialogs).toBe(1)
 await expect(app.locator('body')).not.toHaveAttribute('aria-busy','true')
 await expect(stats.getByRole('button',{name:/^已过期/})).toContainText('1')
 accept=true
 await stats.getByRole('button',{name:'一键删除过期报价',exact:true}).click()
 await expect(app.locator('#q-table tbody')).toContainText('没有符合条件的报价')
 await expect(stats.getByRole('button',{name:/^已过期/})).toContainText('0')
 await stats.getByRole('button',{name:/有效期缺失/}).click()
 await expect(rows).toHaveCount(1)
})

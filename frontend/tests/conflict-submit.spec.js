import {test,expect} from '@playwright/test'
test('conflicts stay in edit, highlighted, one message, corrected rows can submit',async({page})=>{
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe')
 await app.locator('#view-home .entry').nth(1).click()
 const frame=page.frames().find(f=>f.url().includes('quotation.html'))
 await frame.evaluate(()=>{
  pane('edit',2)
  const p=refs.ports.find(p=>p.name_en==='ROTTERDAM')
  for(let i=0;i<3;i++){addRow();Object.assign(editRows[i],fromData({...defaults,destination_port_id:p.id,route_id:p.route_ids[0],prices:{'20GP':String(1800+i)},carrier_id:'carrier-a',currency:'USD',valid_from:'2026-11-01',valid_to:'2026-11-30'}));}
  renderEdit()
 })
 let dialogs=0;page.on('dialog',async d=>{dialogs++;await d.accept()})
 await app.getByRole('button',{name:'提交审批 →',exact:true}).click()
 await expect(app.locator('#edit-table tr.quote-conflict')).toHaveCount(3)
 await expect(app.locator('#pane-edit')).toBeVisible()
 await expect(app.locator('#pane-diff')).toBeHidden()
 expect(dialogs).toBe(1)
 await frame.evaluate(async()=>{await showComparison()})
 await expect(app.locator('#pane-edit')).toBeVisible()
 await expect(app.locator('#pane-diff')).toBeHidden()
 const text=await app.locator('#toast').textContent()
 expect(text.split('批次内存在相互矛盾的报价').length-1).toBe(1)
 await expect(app.locator('#edit-table tr.quote-conflict td').first()).toHaveCSS('background-color','rgb(255, 244, 204)')
 await frame.evaluate(()=>{for(const r of editRows)r.c20='2000';renderEdit()})
 await app.getByRole('button',{name:'提交审批 →',exact:true}).click()
 await expect(app.locator('#pane-diff')).toBeVisible()
 expect(dialogs).toBe(2)
})

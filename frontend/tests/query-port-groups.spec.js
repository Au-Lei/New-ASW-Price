import {test,expect} from '@playwright/test'

test('same port names appear once while all carrier prices and sticky columns remain',async({page})=>{
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe')
 await expect(app.locator('#view-home')).toBeVisible()
 await app.locator('#view-home .entry').first().click()
 const table=app.locator('#q-table')
 await expect(table.locator('tbody tr')).toHaveCount(3)
 await expect(table.locator('tbody td',{hasText:/^ROTTERDAM$/})).toHaveCount(1)
 await expect(table.locator('tbody td',{hasText:/^鹿特丹$/})).toHaveCount(1)
 await expect(table.locator('tbody td',{hasText:/^NETHERLANDS$/})).toHaveCount(1)
 await expect(table.locator('tbody td',{hasText:/^荷兰$/})).toHaveCount(1)
 const merged=table.locator('tbody td',{hasText:/^ROTTERDAM$/})
 await expect(merged).toHaveAttribute('rowspan','2')
 await expect(table.locator('tbody')).toContainText('1200.00')
 await expect(table.locator('tbody')).toContainText('测试船公司b')
 const before=await merged.boundingBox()
 await table.evaluate(t=>{t.parentElement.scrollLeft=650})
 await expect.poll(async()=>Math.abs((await merged.boundingBox()).x-before.x)).toBeLessThan(2)
 await page.setViewportSize({width:1200,height:850})
 await expect(merged).toBeVisible()
 await page.screenshot({path:'/tmp/asw-port-groups-proof.png',fullPage:true})
 await app.locator('#q-carrier').selectOption('carrier-b')
 await app.getByRole('button',{name:'🔍 查询报价',exact:true}).click()
 await expect(table.locator('tbody tr')).toHaveCount(1)
 await expect(table.locator('tbody td',{hasText:/^ROTTERDAM$/})).toHaveAttribute('rowspan','1')
})

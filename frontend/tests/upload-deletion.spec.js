import {test,expect} from '@playwright/test'
test('file and history deletion with cancellation',async({page})=>{
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe')
 await app.locator('#view-home .entry').nth(1).click()
 const file=app.locator('#filelist .fileitem')
 await app.locator('#file-input').setInputFiles('/private/tmp/asw-original-ui-delete-check2/synthetic.xlsx')
 await expect(file).toHaveCount(1)
 page.once('dialog',d=>d.dismiss())
 await file.getByRole('button',{name:'删除',exact:true}).click()
 await expect(file).toHaveCount(1)
 page.once('dialog',d=>d.accept())
 await file.getByRole('button',{name:'删除',exact:true}).click()
 await expect(file).toHaveCount(0)
 await expect(app.locator('#btn-extract')).toBeDisabled()
 await app.locator('#file-input').setInputFiles('/private/tmp/asw-original-ui-delete-check2/synthetic.xlsx')
 await expect(file).toHaveCount(1)
 await app.locator('details summary').click()
 const history=app.locator('#recent-uploads')
 await expect(history.getByRole('button',{name:'删除',exact:true})).toHaveCount(1)
 page.once('dialog',d=>d.dismiss())
 await history.getByRole('button',{name:'删除',exact:true}).click()
 await expect(file).toHaveCount(1)
 page.once('dialog',d=>d.accept())
 await history.getByRole('button',{name:'删除',exact:true}).click()
 await expect(file).toHaveCount(0)
 await expect(history).toContainText('暂无历史上传')
 await page.screenshot({path:'/private/tmp/asw-upload-deletion.png',fullPage:true})
})

import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
test('returning home then uploading only file two does not resume whole old batch',async({page})=>{
 await page.goto('http://127.0.0.1:8004/')
 await page.getByLabel('账号',{exact:true}).fill('admin')
 await page.getByLabel('密码',{exact:true}).fill('Isolated-test-password-2026!')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 const app=page.frameLocator('iframe')
 await app.locator('#view-home .entry').nth(1).click()
 const buffer=readFileSync('/private/tmp/asw-original-ui-upload-isolation/synthetic.xlsx')
 const upload=name=>app.locator('#file-input').setInputFiles({name,mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer: name==='1.xlsx'?Buffer.concat([buffer,Buffer.from('different test bytes')]):buffer})
 await upload('1.xlsx')
 await expect(app.locator('#filelist .fileitem')).toHaveCount(1)
 await upload('2.xlsx')
 await expect(app.locator('#filelist .fileitem')).toHaveCount(2)
 await app.locator('#view-update .back-link').click()
 await app.locator('#view-home .entry').nth(1).click()
 await expect(app.locator('#filelist .fileitem')).toHaveCount(0)
 await upload('2.xlsx')
 await expect(app.locator('#filelist .fileitem')).toHaveCount(1)
 await expect(app.locator('#filelist')).toContainText('2.xlsx')
 await expect(app.locator('#filelist')).not.toContainText('1.xlsx')
 await upload('2.xlsx')
 await expect(app.locator('#filelist .fileitem')).toHaveCount(1)
 await app.locator('details summary').click()
 const history=app.locator('#recent-uploads')
 await expect(history).toContainText('2份文件')
 await history.getByRole('button',{name:/2份文件/}).click()
 await expect(app.locator('#filelist .fileitem')).toHaveCount(2)
})
